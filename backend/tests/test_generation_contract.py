"""Pin the on-the-wire contract between the publisher and the Worker.

The publisher (`pipeline/local_queue_worker.py`) writes `active.json` and the
generation key layout; the Worker (`worker/src/artifact-store.mjs`) parses and
validates them. Nothing else forces those two to agree: each side's own suite
uses its own hand-written fixtures, so a rename or a shape change on one side
leaves both suites green and breaks production.

This module makes the *publisher* emit a real pointer and generation layout into
a fixture file. `worker/tests/generation-contract.test.mjs` reads that same file
and drives the Worker with it. The fixture is regenerated by running this test,
so it can never drift from what the publisher actually produces -- if it does,
the Worker test fails.
"""

from __future__ import annotations

import json
import os
import sys
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from pipeline.local_queue_worker import (
    publication_generation_id,
    publish_active_generation,
    sync_artifacts_to_r2,
)
from pipeline.artifacts import checksum_file, write_json

CONTRACT_FIXTURE = (
    Path(__file__).resolve().parents[2] / "worker" / "tests" / "fixtures" / "generation-contract.json"
)
SESSION_ID = "2026-09-r"


class GenerationContractTests(unittest.TestCase):
    def test_publisher_emits_the_layout_the_worker_parses(self):
        with tempfile.TemporaryDirectory() as temporary_directory:
            output_dir = Path(temporary_directory)
            session_dir = output_dir / "sessions" / SESSION_ID
            summary_path = session_dir / "summary.json"
            write_json(summary_path, {"session_id": SESSION_ID, "meeting": "Contract GP"})
            lap_path = session_dir / "telemetry" / "ver-lap-1.json"
            write_json(lap_path, {"speed": [1, 2, 3]})
            index_path = session_dir / "telemetry" / "index.json"
            write_json(index_path, {"laps": [{"path": "telemetry/ver-lap-1.json"}]})
            write_json(
                session_dir / "manifest.json",
                {
                    "session_id": SESSION_ID,
                    "generated_at": "2026-07-27T00:00:00+00:00",
                    "sections": [
                        {
                            "kind": "summary",
                            "path": f"sessions/{SESSION_ID}/summary.json",
                            "size_bytes": summary_path.stat().st_size,
                            "checksum": checksum_file(summary_path),
                        },
                        {
                            "kind": "telemetry-index",
                            "path": f"sessions/{SESSION_ID}/telemetry/index.json",
                            "size_bytes": index_path.stat().st_size,
                            "checksum": checksum_file(index_path),
                        },
                        {
                            "kind": "telemetry-lap",
                            "path": f"sessions/{SESSION_ID}/telemetry/ver-lap-1.json",
                            "size_bytes": lap_path.stat().st_size,
                            "checksum": checksum_file(lap_path),
                        },
                    ],
                },
            )

            generation_id = publication_generation_id(output_dir, SESSION_ID)
            objects: dict[str, str] = {}

            # newline="" throughout: R2 stores the bytes on disk, and on Windows
            # `write_json` emits CRLF. Universal-newline translation here would
            # make the captured object shorter than the `size_bytes` the pointer
            # records, and the mismatch would look like a publisher bug.
            def fake_upload(path, _bucket, key):
                with Path(path).open("r", encoding="utf-8", newline="") as handle:
                    objects[key] = handle.read()

            def fake_download(_bucket, key, destination, **_kwargs):
                if key not in objects:
                    return False
                with Path(destination).open("w", encoding="utf-8", newline="") as handle:
                    handle.write(objects[key])
                return True

            with (
                patch("pipeline.local_queue_worker.upload_r2_object", side_effect=fake_upload),
                patch(
                    "pipeline.local_queue_worker.download_r2_object", side_effect=fake_download
                ),
            ):
                sync_artifacts_to_r2(
                    output_dir,
                    "contract-bucket",
                    session_id=SESSION_ID,
                    year=2026,
                    include_indexes=False,
                    generation_id=generation_id,
                )
                publish_active_generation(
                    output_dir, "contract-bucket", "", SESSION_ID, generation_id
                )

        # Everything the publisher wrote, exactly as it wrote it. The Worker test
        # loads this as its bucket, so the two sides cannot describe the layout
        # differently and both stay green.
        #
        # Committed and compared rather than regenerated, because CI runs the
        # Python and Worker suites as separate jobs on separate runners: a
        # fixture written here would never reach the job that consumes it. So a
        # publisher-side change to the pointer shape or key layout fails HERE,
        # naming the drift, instead of silently leaving the Worker test
        # validating a contract nobody produces any more.
        rendered = (
            json.dumps(
                {
                    "session_id": SESSION_ID,
                    "generation_id": generation_id,
                    "objects": dict(sorted(objects.items())),
                },
                indent=2,
            )
            + "\n"
        )
        if os.getenv("UPDATE_CONTRACT_FIXTURE"):
            CONTRACT_FIXTURE.parent.mkdir(parents=True, exist_ok=True)
            with CONTRACT_FIXTURE.open("w", encoding="utf-8", newline="\n") as handle:
                handle.write(rendered)
        else:
            self.assertTrue(
                CONTRACT_FIXTURE.is_file(),
                f"{CONTRACT_FIXTURE} is missing; regenerate with UPDATE_CONTRACT_FIXTURE=1",
            )
            # open(newline="") rather than read_text(newline=""): the keyword
            # only reached Path.read_text in 3.13, and CI runs 3.11.
            with CONTRACT_FIXTURE.open("r", encoding="utf-8", newline="") as handle:
                committed = handle.read()
            self.assertEqual(
                committed,
                rendered,
                "The publisher no longer emits the layout worker/tests/"
                "generation-contract.test.mjs is written against. If the change "
                "is intended, re-run with UPDATE_CONTRACT_FIXTURE=1 and check the "
                "Worker still parses the result.",
            )

        pointer_key = f"sessions/{SESSION_ID}/active.json"
        self.assertIn(pointer_key, objects)
        pointer = json.loads(objects[pointer_key])

        # The properties worker/src/artifact-store.mjs `loadActivePointer`
        # enforces. Asserted here too so a publisher-side break is named on the
        # publisher side rather than surfacing as an opaque Worker failure.
        self.assertEqual(pointer["schema_version"], 1)
        self.assertEqual(pointer["session_id"], SESSION_ID)
        self.assertEqual(
            pointer["artifact_base_path"],
            f"sessions/{SESSION_ID}/generations/{generation_id}",
        )
        self.assertEqual(pointer["manifest"]["checksum"], f"sha256:{generation_id}")
        self.assertIsInstance(pointer["manifest"]["size_bytes"], int)
        self.assertEqual(
            pointer["manifest"]["size_bytes"],
            len(objects[f"{pointer['artifact_base_path']}/manifest.json"].encode("utf-8")),
        )

        # No session object was written at a conventional key: the flip, not any
        # individual upload, is what changes what a reader sees.
        self.assertEqual(
            [key for key in objects if key.startswith(f"sessions/{SESSION_ID}/") and "/generations/" not in key],
            [pointer_key],
        )


if __name__ == "__main__":
    unittest.main()
